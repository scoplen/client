import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import process from "node:process";
import { URL } from "node:url";

const directory = process.argv[2];
if (!directory) throw new Error("Usage: node scripts/generate-unicode15.mjs <Unicode-15.0.0-directory> [--check]");

const sources = {
  "UnicodeData.txt": "806e9aed65037197f1ec85e12be6e8cd870fc5608b4de0fffd990f689f376a73",
  "EastAsianWidth.txt": "743e7bc435c04ab1a8459710b1c3cad56eedced5b806b4659b6e69b85d0adf2a",
};
const inputs = {};
for (const [name, checksum] of Object.entries(sources)) {
  const input = readFileSync(join(directory, name));
  if (createHash("sha256").update(input).digest("hex") !== checksum) throw new Error(`Unexpected ${name} checksum`);
  inputs[name] = input.toString("utf8");
}

const zero = new Uint8Array(0x110000);
const wide = new Uint8Array(0x110000);
for (const line of inputs["UnicodeData.txt"].split("\n")) {
  const [point, , category] = line.split(";");
  if (category === "Mn" || category === "Me" || category === "Cf") zero[parseInt(point, 16)] = 1;
}
// Match xterm's existing codepoint-width policy for format characters and Hangul Jamo.
zero[0xad] = 0;
zero.fill(1, 0x1160, 0x1200);
for (const line of inputs["EastAsianWidth.txt"].split("\n")) {
  const match = /^([0-9A-F]+)(?:\.\.([0-9A-F]+))?\s*;\s*([A-Za-z]+)/.exec(line);
  if (match && (match[3] === "W" || match[3] === "F")) {
    wide.fill(1, parseInt(match[1], 16), parseInt(match[2] ?? match[1], 16) + 1);
  }
}
for (let point = 0; point < zero.length; point++) {
  if (zero[point]) wide[point] = 0;
}

function ranges(flags, start, end) {
  const result = [];
  for (let point = start; point < end; point++) {
    if (!flags[point]) continue;
    const first = point;
    while (point + 1 < end && flags[point + 1]) point++;
    result.push(first, point);
  }
  return result;
}

const tables = {
  ZERO_BMP: ranges(zero, 0, 0x10000),
  ZERO_HIGH: ranges(zero, 0x10000, 0x110000),
  WIDE_BMP: ranges(wide, 0, 0x10000),
  WIDE_HIGH: ranges(wide, 0x10000, 0x110000),
};
let output = `// SPDX-License-Identifier: Unicode-3.0
// Generated by scripts/generate-unicode15.mjs from Unicode 15.0.0 UCD.
// Source checksums and policy: see README.md, "Unicode character widths".
// Copyright (c) 1991-2026 Unicode, Inc. See licenses/UNICODE.txt.
`;
for (const [name, values] of Object.entries(tables)) {
  output += `\n// prettier-ignore\nexport const ${name}: readonly number[] = [\n`;
  for (let offset = 0; offset < values.length; offset += 12) {
    output += `  ${values
      .slice(offset, offset + 12)
      .map((value) => `0x${value.toString(16)}`)
      .join(", ")},\n`;
  }
  output += "];\n";
}
const target = new URL("../src/unicode15-data.ts", import.meta.url);
if (process.argv.includes("--check")) {
  if (readFileSync(target, "utf8") !== output) throw new Error("Unicode 15 tables need regeneration");
} else {
  writeFileSync(target, output);
}
