//! Profile-bound publication of a stable native-owned OpenSSH Include wrapper.

use std::{
    fs::{self, File},
    io::{Read as _, Write as _},
    path::PathBuf,
    sync::{Arc, Mutex, Weak},
};

use crate::profile_context::ProfileRequest;
use scoplen_client_core::{
    inventory::{
        Inventory, OpenSshExportChoice, OpenSshGeneratedError as Error, OpenSshGeneratedPreview,
        OpenSshGeneratedResult, OpenSshGeneratedStatus, generated_open_ssh_include_line,
    },
    portable_archive::ArchiveDestination,
    store::Store,
};

const HEADER: &str = "# Generated by Scoplen. Manage this file in Settings > Data.\n";
const GENERATION_MARKER: &str = "Scoplen OpenSSH generation v1\n";

struct Review {
    store: Weak<Store>,
    opening: String,
    target: Option<Vec<u8>>,
    preview: OpenSshGeneratedPreview,
}

#[derive(Default)]
/// Serializes publication and retains one profile-bound, secret-free review in Rust.
pub struct GeneratedOpenSshState {
    review: Mutex<Option<Review>>,
}

struct Scope {
    destination: ArchiveDestination,
    base: PathBuf,
    directory: PathBuf,
    generations: PathBuf,
    active: PathBuf,
}

impl Scope {
    fn new(store: &Arc<Store>) -> Result<Self, Error> {
        let destination = Inventory::new(store.clone()).generated_open_ssh_destination()?;
        let name = match &destination {
            ArchiveDestination::Local => "local".to_owned(),
            ArchiveDestination::Personal { vault_id, .. } => {
                let id = uuid::Uuid::parse_str(vault_id).map_err(|_| Error::ContextChanged)?;
                format!("personal-{id}")
            }
        };
        let base =
            store.data_dir().canonicalize().map_err(|_| Error::ContextChanged)?.join("openssh");
        let directory = base.join(name);
        let active = directory.join("active.conf");
        generated_open_ssh_include_line(&active)?;
        Ok(Self {
            destination,
            generations: directory.join("generations"),
            directory,
            base,
            active,
        })
    }

    fn ensure_directories(&self) -> Result<(), Error> {
        for directory in [&self.base, &self.directory, &self.generations] {
            match fs::create_dir(directory) {
                Ok(()) => (),
                Err(error) if error.kind() == std::io::ErrorKind::AlreadyExists => (),
                Err(_) => return Err(Error::WriteFailed { directory: None }),
            }
            if !fs::symlink_metadata(directory).is_ok_and(|metadata| metadata.file_type().is_dir())
            {
                return Err(Error::TargetChanged);
            }
        }
        Ok(())
    }

    fn wrapper(&self, generation: uuid::Uuid) -> Result<String, Error> {
        let config = self.generations.join(generation.to_string()).join("config");
        Ok(format!(
            "{HEADER}# Generation {generation}\n{}\n",
            generated_open_ssh_include_line(&config)?
        ))
    }

    fn target(&self) -> Result<Option<Vec<u8>>, Error> {
        for directory in [&self.base, &self.directory, &self.generations] {
            match fs::symlink_metadata(directory) {
                Ok(metadata) if metadata.file_type().is_dir() => (),
                Err(error) if error.kind() == std::io::ErrorKind::NotFound => return Ok(None),
                _ => return Err(Error::TargetChanged),
            }
        }
        let metadata = match fs::symlink_metadata(&self.active) {
            Ok(metadata) if metadata.file_type().is_file() => metadata,
            Err(error) if error.kind() == std::io::ErrorKind::NotFound => return Ok(None),
            _ => return Err(Error::TargetChanged),
        };
        if metadata.len() > 16 * 1024 {
            return Err(Error::TargetChanged);
        }
        let mut bytes = Vec::new();
        File::open(&self.active)
            .and_then(|file| file.take(16 * 1024 + 1).read_to_end(&mut bytes))
            .map_err(|_| Error::TargetChanged)?;
        if bytes == HEADER.as_bytes() {
            return Ok(Some(bytes));
        }
        let generation = std::str::from_utf8(&bytes)
            .ok()
            .and_then(|text| text.strip_prefix(HEADER))
            .and_then(|text| text.strip_prefix("# Generation "))
            .and_then(|text| text.split_once('\n'))
            .and_then(|(id, _)| uuid::Uuid::parse_str(id).ok())
            .ok_or(Error::TargetChanged)?;
        if bytes != self.wrapper(generation)?.as_bytes() {
            return Err(Error::TargetChanged);
        }
        Ok(Some(bytes))
    }

    fn status(&self, target: Option<&[u8]>) -> Result<OpenSshGeneratedStatus, Error> {
        Ok(OpenSshGeneratedStatus {
            destination: self.destination.clone(),
            include_path: self.active.to_string_lossy().into_owned(),
            include_line: generated_open_ssh_include_line(&self.active)?,
            active: target.is_some_and(|bytes| bytes != HEADER.as_bytes()),
        })
    }

    fn publish(&self, expected: &Option<Vec<u8>>, contents: &[u8]) -> Result<(), Error> {
        let mut output = tempfile::Builder::new()
            .prefix(".scoplen-include-")
            .suffix(".partial")
            .tempfile_in(&self.directory)
            .map_err(|_| Error::WriteFailed { directory: None })?;
        output
            .write_all(contents)
            .and_then(|()| output.as_file().sync_all())
            .map_err(|_| Error::WriteFailed { directory: None })?;
        if &self.target()? != expected {
            return Err(Error::TargetChanged);
        }
        output.persist(&self.active).map_err(|_| Error::WriteFailed { directory: None })?;
        Ok(())
    }
}

impl GeneratedOpenSshState {
    pub(crate) fn status(&self, store: &Arc<Store>) -> Result<OpenSshGeneratedStatus, Error> {
        let _review = self.review.lock().unwrap_or_else(|error| error.into_inner());
        let scope = Scope::new(store)?;
        scope.status(scope.target()?.as_deref())
    }

    pub(crate) fn preview(
        &self,
        store: &Arc<Store>,
        opening: String,
        choices: Vec<OpenSshExportChoice>,
    ) -> Result<OpenSshGeneratedPreview, Error> {
        let mut review = self.review.lock().unwrap_or_else(|error| error.into_inner());
        *review = None;
        let scope = Scope::new(store)?;
        let target = scope.target()?;
        let preview = Inventory::new(store.clone()).preview_generated_open_ssh(choices)?;
        if preview.destination != scope.destination {
            return Err(Error::ContextChanged);
        }
        *review = Some(Review {
            store: Arc::downgrade(store),
            opening,
            target,
            preview: preview.clone(),
        });
        Ok(preview)
    }

    pub(crate) fn generate(
        &self,
        store: &Arc<Store>,
        opening: &str,
        preview_id: &str,
    ) -> Result<OpenSshGeneratedResult, Error> {
        let mut pending = self.review.lock().unwrap_or_else(|error| error.into_inner());
        let review = pending.take().ok_or(Error::PreviewExpired)?;
        if review.preview.id != preview_id {
            return Err(Error::PreviewExpired);
        }
        if review.opening != opening
            || !review.store.upgrade().is_some_and(|owner| Arc::ptr_eq(store, &owner))
        {
            return Err(Error::ContextChanged);
        }
        let scope = Scope::new(store)?;
        if scope.destination != review.preview.destination {
            return Err(Error::ContextChanged);
        }
        if scope.target()? != review.target {
            return Err(Error::TargetChanged);
        }
        let inventory = Inventory::new(store.clone());
        scope.ensure_directories()?;
        let generation = uuid::Uuid::now_v7();
        let directory = scope.generations.join(generation.to_string());
        let output = inventory.write_generated_open_ssh(&review.preview, &directory)?;
        let result = (|| {
            let mut marker = fs::OpenOptions::new()
                .write(true)
                .create_new(true)
                .open(directory.join(".scoplen-generation"))
                .map_err(|_| Error::WriteFailed { directory: None })?;
            marker
                .write_all(GENERATION_MARKER.as_bytes())
                .and_then(|()| marker.sync_all())
                .map_err(|_| Error::WriteFailed { directory: None })?;
            #[cfg(unix)]
            for path in [directory.join("identities"), directory.clone(), scope.generations.clone()]
            {
                if path.exists() {
                    File::open(path)
                        .and_then(|file| file.sync_all())
                        .map_err(|_| Error::WriteFailed { directory: None })?;
                }
            }
            inventory.recheck_generated_open_ssh(&review.preview)?;
            let wrapper = scope.wrapper(generation)?;
            let status = scope.status(Some(wrapper.as_bytes()))?;
            scope.publish(&review.target, wrapper.as_bytes())?;
            Ok(OpenSshGeneratedResult { status, hosts: output.hosts, files: output.files + 1 })
        })();
        if result.is_err() && fs::remove_dir_all(&directory).is_err() {
            return Err(Error::WriteFailed {
                directory: Some(directory.to_string_lossy().into_owned()),
            });
        }
        result
    }

    fn clear(&self, store: &Arc<Store>) -> Result<OpenSshGeneratedStatus, Error> {
        let mut review = self.review.lock().unwrap_or_else(|error| error.into_inner());
        *review = None;
        let scope = Scope::new(store)?;
        let target = scope.target()?;
        scope.ensure_directories()?;
        // Publish a valid empty Include before deleting any referenced generation.
        scope.publish(&target, HEADER.as_bytes())?;
        let retained =
            || Error::ClearFailed { directory: scope.directory.to_string_lossy().into_owned() };
        for entry in fs::read_dir(&scope.generations).map_err(|_| retained())? {
            let entry = entry.map_err(|_| retained())?;
            if !entry.file_type().map_err(|_| retained())?.is_dir()
                || entry
                    .file_name()
                    .to_str()
                    .is_none_or(|name| uuid::Uuid::parse_str(name).is_err())
            {
                continue;
            }
            let marker = entry.path().join(".scoplen-generation");
            match fs::symlink_metadata(&marker) {
                Ok(metadata)
                    if metadata.file_type().is_file()
                        && metadata.len() == GENERATION_MARKER.len() as u64 => {}
                Ok(_) => continue,
                Err(error) if error.kind() == std::io::ErrorKind::NotFound => continue,
                Err(_) => return Err(retained()),
            }
            if fs::read(&marker).map_err(|_| retained())? != GENERATION_MARKER.as_bytes() {
                continue;
            }
            fs::remove_dir_all(entry.path()).map_err(|_| retained())?;
        }
        scope.status(Some(HEADER.as_bytes()))
    }

    fn discard(&self) {
        self.review.lock().unwrap_or_else(|error| error.into_inner()).take();
    }
}

/// Report the current profile's stable native-owned Include path.
#[tauri::command]
#[specta::specta]
pub async fn generated_open_ssh_status(
    local: ProfileRequest,
    state: tauri::State<'_, Arc<GeneratedOpenSshState>>,
) -> Result<OpenSshGeneratedStatus, Error> {
    let state = state.inner().clone();
    tauri::async_runtime::spawn_blocking(move || {
        local.with_store(|store| state.status(store)).unwrap_or(Err(Error::ContextChanged))
    })
    .await
    .map_err(|_| Error::ContextChanged)?
}

/// Review complete scoped compatibility and friendly aliases before publication.
#[tauri::command]
#[specta::specta]
pub async fn generated_open_ssh_preview(
    local: ProfileRequest,
    state: tauri::State<'_, Arc<GeneratedOpenSshState>>,
    choices: Option<Vec<OpenSshExportChoice>>,
) -> Result<OpenSshGeneratedPreview, Error> {
    let state = state.inner().clone();
    tauri::async_runtime::spawn_blocking(move || {
        let opening = local.generation();
        local
            .with_store(|store| state.preview(store, opening, choices.unwrap_or_default()))
            .unwrap_or(Err(Error::ContextChanged))
    })
    .await
    .map_err(|_| Error::ContextChanged)?
}

/// Consume the captured native review and atomically publish its complete generation.
#[tauri::command]
#[specta::specta]
pub async fn generated_open_ssh_generate(
    local: ProfileRequest,
    state: tauri::State<'_, Arc<GeneratedOpenSshState>>,
    preview_id: String,
) -> Result<OpenSshGeneratedResult, Error> {
    let state = state.inner().clone();
    tauri::async_runtime::spawn_blocking(move || {
        let opening = local.generation();
        local
            .with_store(|store| state.generate(store, &opening, &preview_id))
            .unwrap_or(Err(Error::ContextChanged))
    })
    .await
    .map_err(|_| Error::ContextChanged)?
}

/// Publish an empty wrapper, then remove only this scope's marked generations.
#[tauri::command]
#[specta::specta]
pub async fn generated_open_ssh_clear(
    local: ProfileRequest,
    state: tauri::State<'_, Arc<GeneratedOpenSshState>>,
) -> Result<OpenSshGeneratedStatus, Error> {
    let state = state.inner().clone();
    tauri::async_runtime::spawn_blocking(move || {
        local.with_store(|store| state.clear(store)).unwrap_or(Err(Error::ContextChanged))
    })
    .await
    .map_err(|_| Error::ContextChanged)?
}

/// Discard a review off the main thread without deleting generated output.
#[tauri::command]
#[specta::specta]
pub async fn generated_open_ssh_discard(
    local: ProfileRequest,
    state: tauri::State<'_, Arc<GeneratedOpenSshState>>,
) -> Result<(), Error> {
    let state = state.inner().clone();
    tauri::async_runtime::spawn_blocking(move || {
        local.with_store(|_| state.discard()).ok_or(Error::ContextChanged)
    })
    .await
    .map_err(|_| Error::ContextChanged)?
}

